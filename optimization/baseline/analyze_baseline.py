"""Recompute Baseline V0 statistics/figures; never run or modify the benchmark.

Python standard library handles all statistics. Matplotlib is needed for figures.
Input CSV files are immutable evidence: no filtering, smoothing or rewriting.
"""
from __future__ import annotations

import csv
import hashlib
import json
import math
from pathlib import Path
import statistics

BASE = Path(__file__).resolve().parent
FIELDS = ["iteration", "kernel_ms", "checksum", "width", "height", "steps",
          "shadow_size", "shadows", "density", "albedo", "g", "max_distance"]
PARAMETERS = FIELDS[3:]


def percentile(values: list[float], p: float) -> float:
    """Linear interpolation at (n-1)*p (Hyndman-Fan type 7)."""
    ordered = sorted(values)
    position = (len(ordered) - 1) * p
    lower = math.floor(position)
    upper = math.ceil(position)
    return ordered[lower] + (position - lower) * (ordered[upper] - ordered[lower])


def describe(name: str, values: list[float]) -> dict:
    mean = statistics.mean(values)
    sd = statistics.stdev(values)  # Sample standard deviation: denominator n-1.
    return dict(series=name, n=len(values), mean_ms=mean,
                median_ms=statistics.median(values), min_ms=min(values),
                max_ms=max(values), sample_sd_ms=sd, cv_percent=100 * sd / mean,
                p05_ms=percentile(values, .05), q25_ms=percentile(values, .25),
                q75_ms=percentile(values, .75), p95_ms=percentile(values, .95),
                p99_ms=percentile(values, .99), kernel_total_ms=math.fsum(values))


def read_inputs() -> tuple[list, dict, str]:
    # The manifest is fixed evidence, not regenerated by this analysis script.
    # Check archived copies only: original machine-specific paths are optional.
    manifest = json.loads((BASE / "metadata" / "artifacts.json").read_text(encoding="utf-8"))
    for artifact in manifest:
        if artifact["archived"] is not None:
            path = BASE / artifact["archived"]
            if hashlib.sha256(path.read_bytes()).hexdigest() != artifact["sha256"]:
                raise ValueError(f"Archived evidence changed: {path}")
    runs = []
    common_parameters = None
    common_checksum = None
    for number in range(1, 6):
        path = BASE / "results" / f"baseline_{number:02}.csv"
        with path.open(encoding="utf-8-sig", newline="") as stream:
            reader = csv.DictReader(stream)
            if reader.fieldnames != FIELDS:
                raise ValueError(f"Unexpected CSV schema: {path}")
            rows = list(reader)
        if len(rows) != 1000:
            raise ValueError(f"Expected 1000 measured iterations: {path}")
        if [int(row["iteration"]) for row in rows] != list(range(1, 1001)):
            raise ValueError(f"Missing, duplicated or unordered iteration: {path}")
        values = [float(row["kernel_ms"]) for row in rows]
        if not all(math.isfinite(value) and value > 0 for value in values):
            raise ValueError(f"Invalid timing: {path}")
        parameters = {key: rows[0][key] for key in PARAMETERS}
        checksum = rows[0]["checksum"]
        if not math.isfinite(float(checksum)):
            raise ValueError(f"Non-finite checksum: {path}")
        for row in rows:
            if None in row or any(row[key] != parameters[key] for key in PARAMETERS):
                raise ValueError(f"Malformed row or changing parameters: {path}")
            if row["checksum"] != checksum:
                raise ValueError(f"Changing checksum: {path}")
        if common_parameters is not None and parameters != common_parameters:
            raise ValueError("Benchmark parameters differ between runs")
        if common_checksum is not None and checksum != common_checksum:
            raise ValueError("Checksums differ between runs")
        common_parameters, common_checksum = parameters, checksum
        runs.append(dict(name=path.stem, values=values,
                         sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
                         statistics=describe(path.stem, values)))
    return runs, common_parameters, common_checksum


def figures(runs: list, pooled: dict) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    chart_dir = BASE / "charts"
    chart_dir.mkdir(exist_ok=True)
    plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 10,
                         "axes.spines.top": False, "axes.spines.right": False,
                         "savefig.facecolor": "white"})
    colors = ["#16697a", "#cd6327", "#6460a6", "#20805a", "#b04e75"]
    fig, axes = plt.subplots(5, 1, figsize=(11, 10), sharex=True, sharey=True,
                             layout="constrained")
    for ax, run, color in zip(axes, runs, colors):
        ax.plot(range(1, 1001), run["values"], color=color, linewidth=.65)
        ax.axhline(run["statistics"]["median_ms"], color="#263238",
                   linestyle="--", linewidth=1, label="medijan serije")
        ax.set_ylabel("ms")
        ax.set_title(run["name"], loc="left", fontsize=11)
        ax.grid(axis="y", alpha=.18)
    axes[0].legend(loc="upper right")
    axes[-1].set_xlabel("Redni broj mjerene integracije unutar pokretanja")
    axes[-1].set_xlim(1, 1000)
    fig.suptitle("Baseline V0: svih 5.000 mjerenja bez profilera\n"
                 "Ista skala; visoke vrijednosti nisu uklonjene", fontsize=14)
    fig.savefig(chart_dir / "iteration-times.png", dpi=170)
    plt.close(fig)

    fig, axes = plt.subplots(1, 2, figsize=(12, 5), layout="constrained")
    artists = axes[0].boxplot([run["values"] for run in runs],
                              tick_labels=[f"{i:02}" for i in range(1, 6)],
                              patch_artist=True, showmeans=True,
                              flierprops={"markersize": 2.5, "alpha": .5})
    for box, color in zip(artists["boxes"], colors):
        box.set_facecolor(color)
        box.set_alpha(.65)
    axes[0].set_xlabel("Serija baseline_XX")
    axes[0].set_ylabel("Vrijeme CPU integracije [ms]")
    axes[0].set_title("Raspodjele po pokretanju")
    axes[0].grid(axis="y", alpha=.18)
    values = [value for run in runs for value in run["values"]]
    axes[1].hist(values, bins=80, color="#16697a", edgecolor="white", linewidth=.4)
    axes[1].set_yscale("log")
    axes[1].axvline(pooled["mean_ms"], color="#cd6327", linewidth=1.5,
                   label=f"prosjek {pooled['mean_ms']:.4f} ms")
    axes[1].axvline(pooled["median_ms"], color="#263238", linestyle="--",
                   label=f"medijan {pooled['median_ms']:.4f} ms")
    axes[1].set_xlabel("Vrijeme CPU integracije [ms]")
    axes[1].set_ylabel("Broj mjerenja (logaritamska skala)")
    axes[1].set_title("Objedinjeno: svih 5.000 vrijednosti")
    axes[1].legend(fontsize=9)
    fig.suptitle("Baseline V0: varijabilnost i desni rep raspodjele", fontsize=14)
    fig.savefig(chart_dir / "distributions.png", dpi=170)
    plt.close(fig)

    # Transcription of screenshot call-graph.png, EXCLUSIVE samples only.
    names = ["Integrate (vlastito vrijeme)", "exp", "Intersect", "Checksum",
             "expf (vlastito vrijeme)", "MakeWindowRoom (vlastito)", "ntoskrnl (uzorci)"]
    seconds = [25.55, 1.92, .20, .13, .06, .02, .01]
    fig, ax = plt.subplots(figsize=(11, 4.5), layout="constrained")
    ax.barh(names[::-1], seconds[::-1], color=["#7c929b"] * 6 + ["#16697a"])
    for index, value in enumerate(seconds[::-1]):
        ax.text(value + .16, index, f"{value:.2f} s ({value/27.89*100:.2f}%)", va="center")
    ax.set_xlim(0, 30)
    ax.set_xlabel("Ekskluzivno uzorkovano CPU vrijeme [s]")
    ax.set_title("uProf Hotspots: prepis sa screenshota, ne CSV benchmark vremena\n"
                 "Inclusive vrijednosti nisu dodane; ukupan CPU_TIME = 27,89 s")
    ax.grid(axis="x", alpha=.18)
    fig.savefig(chart_dir / "profiler-exclusive.png", dpi=170)
    plt.close(fig)


def main() -> None:
    runs, parameters, checksum = read_inputs()
    values = [value for run in runs for value in run["values"]]
    pooled = describe("ALL_5000", values)
    means = [run["statistics"]["mean_ms"] for run in runs]
    medians = [run["statistics"]["median_ms"] for run in runs]
    summary = dict(
        dataset="Baseline V0: five unprofiled runs", parameters_raw_csv=parameters,
        checksum=checksum, checksum_unique_count=1,
        percentile_method="linear interpolation at (n-1)*p, type 7",
        standard_deviation="sample, denominator n-1", filtering="none",
        runs=[dict(name=run["name"], sha256=run["sha256"], **run["statistics"])
              for run in runs], pooled=pooled,
        between_runs=dict(sample_sd_of_means_ms=statistics.stdev(means),
                          mean_range_percent=100 * (max(means)/min(means) - 1),
                          median_range_percent=100 * (max(medians)/min(medians) - 1),
                          median_of_run_medians_ms=statistics.median(medians)),
        diagnostic=dict(count_above_40_ms=sum(value > 40 for value in values),
                        halves=[dict(series=run["name"],
                                     first_500_mean_ms=statistics.mean(run["values"][:500]),
                                     last_500_mean_ms=statistics.mean(run["values"][500:]))
                                for run in runs]))
    results = BASE / "results"
    (results / "summary.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2)+"\n", encoding="utf-8")
    rows = [run["statistics"] for run in runs] + [pooled]
    with (results / "statistics.csv").open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    table = ["| Serija | N | Prosjek [ms] | Medijan [ms] | Min [ms] | Max [ms] | SD [ms] | CV [%] |",
             "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"]
    for row in rows:
        label = "**Svih 5.000**" if row["series"] == "ALL_5000" else f"`{row['series']}`"
        numbers = [row[key] for key in ("mean_ms", "median_ms", "min_ms", "max_ms", "sample_sd_ms", "cv_percent")]
        formatted = " | ".join(f"{number:.5f}".replace(".", ",") for number in numbers)
        table.append(f"| {label} | {row['n']} | {formatted} |")
    (results / "summary-table.md").write_text("\n".join(table)+"\n", encoding="utf-8")
    (results / "SHA256SUMS.txt").write_text("".join(
        f"{run['sha256']}  {run['name']}.csv\n" for run in runs), encoding="utf-8")
    figures(runs, pooled)
    print("Validated: 5 x 1000 rows, sequential indices, finite positive timings,")
    print("identical parameters and checksum; no values dropped or changed.")
    print(f"Pooled mean={pooled['mean_ms']:.8f} ms, median={pooled['median_ms']:.8f} ms,")
    print(f"sample SD={pooled['sample_sd_ms']:.8f} ms, CV={pooled['cv_percent']:.6f}%")


if __name__ == "__main__":
    main()
